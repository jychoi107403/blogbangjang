<li><strong>에디터 네이티브 수정</strong>: AI가 단순히 채팅창에서 코드를 텍스트로 보여주는 것이 아니라, 내 실제 코드 파일에서 바뀌어야 할 부분을 'Git Diff' 형태로 보여주며 원클릭으로 승인(Accept)할 수 있게 해줍니다.</li>
<li><strong>멀티 파일 수정 (Composer)</strong>: 하나의 프롬프트로 3~5개의 연관된 파일들을 동시에 생성하고 수정하는 마법 같은 작업이 가능합니다.</li>
