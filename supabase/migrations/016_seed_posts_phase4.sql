<h2>반드시 알아야 할 Cursor의 3가지 핵심 기능</h2>
<p>Cursor를 설치했다면 다음 세 가지 기능만 익혀도 코딩 생산성이 즉시 3배 이상 향상됩니다.</p>

<h3>1. Ctrl + K (Mac은 Cmd + K): 인라인 코드 생성 및 편집</h3>
<p>코드 편집기 안에서 수정하고 싶은 코드 블록을 마우스로 드래그한 뒤 <code>Ctrl + K</code>를 누르면 작은 프롬프트 입력창이 뜹니다. 여기에 자연어로 원하는 수정을 요청하면 됩니다.</p>
<p>예를 들어 다음과 같은 요청이 가능합니다:</p>
<ul>
<li>"이 함수에 에러 처리를 위한 try-catch 블록과 한글 주석을 추가해줘."</li>
<li>"이 반복문을 map과 filter 함수를 사용한 함수형 코드로 리팩토링해줘."</li>
<li>"사용자 나이가 0 이하일 때 안내 문구를 출력하는 유효성 검사 로직을 넣어줘."</li>
</ul>
<p>요청 후 수초 안에 초록색(추가)과 빨간색(삭제)으로 변경 사항이 표시되며, <code>Ctrl + Enter</code> 한 번으로 즉시 반영됩니다.</p>

<h3>2. Ctrl + L (Mac은 Cmd + L): 스마트 채팅 & @ 심볼 멘션</h3>
<p>화면 오른쪽에 AI 챗봇 패널이 열립니다. 단순한 대화창이 아니라, <strong>골뱅이(@) 심볼</strong>을 사용하여 원하는 맥락(Context)을 정밀하게 지정할 수 있는 것이 핵심입니다.</p>
<ul>
<li><code>@Files</code>: 특정 파일을 지정하여 해당 파일의 내용을 기반으로 질문합니다 (예: <code>@schema.sql 이 테이블 구조를 바탕으로 타입스크립트 인터페이스를 만들어줘</code>).</li>
<li><code>@Codebase</code>: 프로젝트 전체를 검색하여 가장 연관성 높은 파일들을 AI가 스스로 찾아서 답변을 작성합니다.</li>
<li><code>@Docs</code>: Next.js, Supabase, TailwindCSS 등 공식 기술 문서를 지정하여 최신 문법에 맞게 질문할 수 있습니다.</li>
<li><code>@Git</code>: 최근 커밋 로그나 변경 사항의 차이점을 AI에게 분석하도록 요청합니다.</li>
</ul>

<h3>3. Composer (Ctrl + I / Cmd + I): 설계부터 멀티 파일 생성까지</h3>
<p>Cursor의 진정한 필살기는 바로 Composer 기능입니다. 작은 코드 수정이 아니라 "새로운 기능 하나를 통째로 개발"할 때 사용합니다.</p>
<p>예를 들어 "블로그 상세 페이지 하단에 조회수 증가 기능과 연관 글 추천 카드를 3개 보여주는 기능을 구현해줘"라고 입력하면, Composer는 데이터베이스 쿼리 함수, API 라우트, React 컴포넌트, CSS 스타일 파일까지 필요한 파일들을 알아서 생성하고 수정해줍니다. 개발자는 AI가 제안한 변경 사항들을 검토하고 일괄 수락하기만 하면 됩니다.</p>

<h2>생산성을 10배로 높이는 `.cursorrules` 설정법</h2>
<p>Cursor를 전문가처럼 쓰기 위한 최고의 비결은 프로젝트 루트 폴더에 <code>.cursorrules</code> 파일을 만드는 것입니다. 이 파일은 AI가 코드를 작성할 때 항상 지켜야 할 '기본 행동 강령'을 정의합니다.</p>
<p>예를 들어 다음과 같이 작성해둘 수 있습니다:</p>
<pre><code># 프로젝트 코딩 규칙
